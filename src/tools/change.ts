/**
 * Responsibility: Public tools for bounded workspace reads and previewed changes.
 * Scope: Exposes `read_workspace_file`, `preview_change` and `apply_change` in commandRegistry under category 'change'.
 */

import fs from 'node:fs';
import path from 'node:path';
import { workspacePath } from '../helpers/workspace-path.ts';
import { z } from 'zod';
import { commandRegistry, type ToolContext } from './registry.ts';
import { CodeMutationService } from '../services/code-mutation-service.ts';
import type {SourceChangeRequest} from '../services/code-mutation-service.ts';
import {SourceManager} from '../managers/source-manager.ts';
import {previewProductChange, applyProductChange} from '../product/change-operations.ts';
import type { ChangeRequest } from '../change/types.ts';

import {ChangeRequestSchema} from './change-request.ts';
export {ChangeRequestSchema} from './change-request.ts';
export {CodeChangeRequestSchema} from '../services/code-mutation/request-schema.ts';

export const DirtyTargetsSchema = z.array(z.string().min(1)).max(256).optional();
const previewOptions = ChangeRequestSchema.options.map(schema => schema.extend({ticketId: z.string().min(1).optional(), agentId: z.string().min(1).optional(), allowDirtyTargets: DirtyTargetsSchema}).strict());

export function registerChangeTools() {
  commandRegistry.register({
    name: 'read_workspace_file',
    description: 'Read an existing regular workspace file, up to 64 KiB, without shell execution.',
    category: 'change',
    parameters: z.object({ filePath: z.string().min(1) }),
    execute: async ({ filePath }, ctx: ToolContext) => {
      if (path.isAbsolute(filePath)) throw new Error('Workspace path must be relative.');
      const relative = workspacePath(ctx.projectRoot, filePath);
      const absolute = path.resolve(ctx.projectRoot, relative);
      const descriptor = fs.openSync(absolute, fs.constants.O_RDONLY | fs.constants.O_NONBLOCK);
      try {
        const stat = fs.fstatSync(descriptor);
        if (!stat.isFile()) throw new Error('Workspace target must be an existing regular file.');
        if (stat.size > 65536) throw new Error('Workspace file exceeds the 64 KiB read limit.');
        const content = Buffer.alloc(65537);
        let length = 0, bytes = 0;
        do { bytes = fs.readSync(descriptor, content, length, content.length - length, null); length += bytes; } while (bytes && length < content.length);
        if (length > 65536) throw new Error('Workspace file exceeds the 64 KiB read limit.');
        return { filePath: relative, content: content.subarray(0, length).toString('utf8') };
      } finally { fs.closeSync(descriptor); }
    }
  });
  commandRegistry.register({
    name: 'preview_change',
    description: 'Preview code or Product Intent mutations with zero write side effects.',
    category: 'change',
    parameters: z.discriminatedUnion('action', [previewOptions[0]!, ...previewOptions.slice(1)]),
    execute: async ({ticketId, agentId, allowDirtyTargets, ...request}, ctx: ToolContext) => {
      if (request.action === 'product_change') {
        if (allowDirtyTargets?.length) throw Error('Dirty targets require a governed source Ticket and active lease.');
        return previewProductChange(ctx.store, request as Extract<ChangeRequest, {action: 'product_change'}>);
      }
      const manager = new SourceManager({store: ctx.store, projectRoot: ctx.projectRoot, codeMutationAllowed: ctx.codeMutationAllowed});
      return manager.previewSourceChange(request as SourceChangeRequest, {ticketId, agentId, allowDirtyTargets});
    }
  });

  commandRegistry.register({
    name: 'apply_change',
    description: 'Safely commit a previewed change mutation to disk using its verified preview fingerprint.',
    category: 'change',
    parameters: z.object({
      request: ChangeRequestSchema,
      ticketId: z.string().min(1).optional(),
      agentId: z.string().min(1).optional(),
      allowDirtyTargets: DirtyTargetsSchema,
      fingerprint: z.string().min(1).describe('SHA-256 fingerprint generated by preview_change'),
      decision: z.enum(['accept', 'reject', 'cancel']).optional().describe('Explicit developer review decision; required for Product changes')
    }),
    execute: async ({ request, fingerprint, decision, ticketId, agentId, allowDirtyTargets }, ctx: ToolContext) => {
      if (request.action === 'product_change') {
        if (allowDirtyTargets?.length) throw Error('Dirty targets are only valid for governed source changes.');
        if (!decision) throw new Error('Product application requires explicit developer approval (decision).');
        if (decision !== 'accept') return {ok: false, fingerprint, filesTouched: [], filesRenamed: [], reindexedFiles: [], migratedAnchors: [],
          verification: {passed: false, errors: []}, error: `Product proposal ${decision === 'reject' ? 'rejected' : 'cancelled'}; no changes applied.`};
      }
      if (request.action === 'product_change') {
        return applyProductChange(ctx.store, request as Extract<ChangeRequest, {action: 'product_change'}>, fingerprint);
      }
      const manager = new SourceManager({store: ctx.store, projectRoot: ctx.projectRoot, codeMutationAllowed: ctx.codeMutationAllowed});
      return manager.applySourceChange(request as SourceChangeRequest, fingerprint, {ticketId, agentId, allowDirtyTargets});
    }
  });
}

/** Internal owners of reviewed Story-test source/metadata retain their existing change-engine lifecycle. */
export function applyOwnedChange(preview: import('../change/types.ts').ChangePreview, ctx: ToolContext) {
  return preview.request.action === 'product_change'
    ? applyProductChange(ctx.store, preview.request, preview.fingerprint)
    : new CodeMutationService({store: ctx.store, projectRoot: ctx.projectRoot, codeMutationAllowed: ctx.codeMutationAllowed}).applyCodeChange(preview.request, preview.fingerprint);
}
