/**
 * Responsibility: Rule persistence, scoped override resolution, bundled defaults installation, and startup checks.
 * Scope: Manages Rule entities within Semantika WorkflowStore; resolves effective rules across universal, project, and module scopes.
 */

import { WorkflowStore } from '../graph/store.ts';
import { Rule } from '../graph/ontology.ts';
import {
  RuleSchema,
  RulePackSchema,
  type RuleModel,
  type RulePack,
  type ResolvedRule,
  type RuleScope
} from './types.ts';
import defaultsData from './defaults.json' with { type: 'json' };

export class RuleStore {
  constructor(public readonly store: WorkflowStore) {}

  /**
   * Generates a collision-free graph entity ID for a Rule layer:
   * rule-hex(<json([ruleId, scopeKind, moduleId])>)
   * Because WorkflowStore.formatId() replaces underscores with hyphens, hexadecimal encoding
   * guarantees that the encoded string contains only [0-9a-f], surviving formatId() and localId()
   * 100% losslessly without collision or character corruption.
   */
  static entityIdForScope(ruleId: string, scope: RuleScope): string {
    const tuple = [ruleId, scope.kind, scope.kind === 'module' ? scope.moduleId : ''];
    const hex = Buffer.from(JSON.stringify(tuple), 'utf8').toString('hex');
    return `rule-${hex}`;
  }

  /**
   * Decodes an entity ID generated by entityIdForScope().
   * Returns null if the entity ID is not in the rule-hex format.
   */
  static decodeEntityId(id: string): { ruleId: string; scope: RuleScope } | null {
    const raw = id.startsWith('rule-') ? id.slice(5) : id;
    try {
      const json = Buffer.from(raw, 'hex').toString('utf8');
      const [ruleId, kind, moduleId] = JSON.parse(json);
      const scope: RuleScope = kind === 'module' ? { kind: 'module', moduleId } : { kind };
      return { ruleId, scope };
    } catch {
      return null;
    }
  }

  /**
   * Parse and validate a raw rule record according to RuleSchema.
   */
  static validateRule(raw: unknown): RuleModel {
    return RuleSchema.parse(raw);
  }

  /**
   * Save or update an individual Rule in the graph.
   */
  async saveRule(model: RuleModel): Promise<Rule> {
    const validated = RuleStore.validateRule(model);
    const entityId = RuleStore.entityIdForScope(validated.ruleId, validated.scope);
    
    const payload = {
      ...validated,
      id: entityId,
      _id: entityId,
      title: validated.title ?? validated.ruleId
    };

    return this.store.upsertEntity<Rule>(Rule.dcr, payload);
  }

  /**
   * Retrieve a specific Rule entity by ruleId and scope.
   */
  async getRule(ruleId: string, scope: RuleScope): Promise<RuleModel | null> {
    const entityId = RuleStore.entityIdForScope(ruleId, scope);
    const entity = await this.store.getEntity<Rule>(entityId, Rule.dcr);
    if (!entity) return null;
    return this.entityToModel(entity);
  }

  /**
   * List all stored Rule entities across all scopes.
   */
  async listAllRules(): Promise<RuleModel[]> {
    const entities = await this.store.listEntities<Rule>(Rule.dcr);
    return entities.map(e => this.entityToModel(e));
  }

  /**
   * Converts a Semantika Rule entity to a validated RuleModel.
   */
  private entityToModel(entity: Rule): RuleModel {
    const localId = this.store.localId(entity.id);
    const decoded = RuleStore.decodeEntityId(localId);
    const defaultRuleId = entity.ruleId || decoded?.ruleId || localId;
    const defaultScope = entity.scope || decoded?.scope || { kind: 'universal' };

    return RuleSchema.parse({
      id: localId,
      ruleId: defaultRuleId,
      title: entity.title,
      type: entity.type,
      scope: defaultScope,
      importance: entity.importance,
      rule: entity.rule,
      status: entity.status,
      disableReason: entity.disableReason,
      languages: entity.languages,
      examples: entity.examples ?? [],
      references: entity.references ?? [],
      test: entity.test,
      revision: entity.revision ?? 1,
      provenance: entity.provenance ?? 'unknown'
    });
  }

  /**
   * Folds candidates for a single logical ruleId into an effective ResolvedRule.
   * Rules:
   * 1. Language applicability: candidates with explicit language restrictions must match context.language
   *    before participating in scope folding, so a language-specific override (e.g., Python-only) does not
   *    suppress an otherwise applicable inherited rule in another language context (e.g., TypeScript).
   * 2. Precedence: module > project > universal.
   * 3. Draft rules cannot shadow active inherited rules (drafts are ignored if an active lower layer exists).
   * 4. Disabled rules represent explicit suppression and shadow lower layers with isDisabled = true.
   */
  static foldRuleLayers(
    ruleId: string,
    candidates: RuleModel[],
    context: { moduleId?: string; language?: string } = {}
  ): ResolvedRule | null {
    if (candidates.length === 0) return null;

    // Filter candidates by language applicability BEFORE scope folding
    const languageApplicable = candidates.filter(r => {
      if (!context.language || !r.languages || r.languages.length === 0) {
        return true;
      }
      return r.languages.includes(context.language);
    });

    if (languageApplicable.length === 0) return null;

    const universal = languageApplicable.find(r => r.scope.kind === 'universal');
    const project = languageApplicable.find(r => r.scope.kind === 'project');
    const moduleCandidate = context.moduleId
      ? languageApplicable.find(r => r.scope.kind === 'module' && r.scope.moduleId === context.moduleId)
      : undefined;

    const layers: RuleModel[] = [];
    if (universal) layers.push(universal);
    if (project) layers.push(project);
    if (moduleCandidate) layers.push(moduleCandidate);

    if (layers.length === 0) return null;

    // Evaluate candidates from most specific to least specific:
    // [moduleCandidate, project, universal]
    const candidatesDesc = [moduleCandidate, project, universal].filter((r): r is RuleModel => Boolean(r));

    // Draft rules cannot shadow active inherited rules.
    // If the top layer is 'draft', find if there is an active/disabled inherited layer.
    let effective = candidatesDesc[0];
    if (effective.status === 'draft') {
      const activeOrDisabled = candidatesDesc.find(r => r.status === 'active' || r.status === 'disabled');
      if (activeOrDisabled) {
        effective = activeOrDisabled;
      }
    }

    const inheritedFrom = effective === moduleCandidate
      ? (project ? 'project' : universal ? 'universal' : undefined)
      : (effective === project && universal ? 'universal' : undefined);

    const isOverridden = layers.length > 1;
    const isDisabled = effective.status === 'disabled';

    return {
      ruleId,
      effective,
      layers,
      inheritedFrom,
      isOverridden,
      isDisabled
    };
  }

  /**
   * Resolves the effective rule definition for a given ruleId and target scope context.
   */
  async resolveRule(ruleId: string, context: { moduleId?: string; language?: string } = {}): Promise<ResolvedRule | null> {
    const all = await this.listAllRules();
    const candidates = all.filter(r => r.ruleId === ruleId);
    return RuleStore.foldRuleLayers(ruleId, candidates, context);
  }

  /**
   * Resolves all effective rules applicable to a given target context.
   * Performs ONE single collection read across all stored rules.
   * If forGovernance is true (the default when delivering doctrine to Actors/Verifiers):
   * excludes standalone draft rules whose effective state remains draft.
   */
  async resolveAllRules(context: { moduleId?: string; language?: string; forGovernance?: boolean } = {}): Promise<ResolvedRule[]> {
    const forGovernance = context.forGovernance ?? true;
    const all = await this.listAllRules();
    
    // Group all rules by ruleId in memory
    const grouped = new Map<string, RuleModel[]>();
    for (const rule of all) {
      const list = grouped.get(rule.ruleId) ?? [];
      list.push(rule);
      grouped.set(rule.ruleId, list);
    }

    const resolved: ResolvedRule[] = [];
    const sortedRuleIds = [...grouped.keys()].sort();

    for (const ruleId of sortedRuleIds) {
      const candidates = grouped.get(ruleId) ?? [];
      const res = RuleStore.foldRuleLayers(ruleId, candidates, context);
      if (!res) continue;

      // When resolving for governance (Actors/Verifiers), standalone draft rules do not enforce
      if (forGovernance && res.effective.status === 'draft') {
        continue;
      }

      resolved.push(res);
    }

    return resolved;
  }

  /**
   * Verify whether bundled defaults are installed, up-to-date, or customized/conflicting.
   * Distinguishes:
   * - missing: bundled rule has no universal record in the graph.
   * - outdated: authentic bundled default exists with lower revision.
   * - customized: universal record exists with user/local customization (provenance !== 'bundled-default' or modified body).
   * - authentic: installed universal default matching bundled revision and provenance.
   */
  async checkDefaultsInstalled(): Promise<{
    complete: boolean;
    upToDate: boolean;
    hasCustomizedConflicts: boolean;
    missingRuleIds: string[];
    outdatedRuleIds: string[];
    customizedRuleIds: string[];
    installedCount: number;
    expectedCount: number;
  }> {
    const pack = RulePackSchema.parse(defaultsData);
    const existing = await this.listAllRules();
    const existingUniversal = new Map(
      existing.filter(r => r.scope.kind === 'universal').map(r => [r.ruleId, r])
    );

    const missingRuleIds: string[] = [];
    const outdatedRuleIds: string[] = [];
    const customizedRuleIds: string[] = [];

    for (const rule of pack.rules) {
      const current = existingUniversal.get(rule.ruleId);
      if (!current) {
        missingRuleIds.push(rule.ruleId);
      } else if (current.provenance !== 'bundled-default') {
        customizedRuleIds.push(rule.ruleId);
      } else if (current.revision < rule.revision) {
        outdatedRuleIds.push(rule.ruleId);
      }
    }

    const complete = missingRuleIds.length === 0;
    const upToDate = complete && outdatedRuleIds.length === 0;

    return {
      complete,
      upToDate,
      hasCustomizedConflicts: customizedRuleIds.length > 0,
      missingRuleIds,
      outdatedRuleIds,
      customizedRuleIds,
      installedCount: pack.rules.length - missingRuleIds.length,
      expectedCount: pack.rules.length
    };
  }

  /**
   * Ensure bundled defaults are installed in the graph.
   * Strictly preserves any existing universal, project, or module rules.
   * Does NOT perform destructive automatic upgrades on existing universal records;
   * reports available updates and conflicts instead. Full governed import/upgrade
   * is deferred to Gate 4.
   */
  async installDefaults(): Promise<{
    installed: number;
    upgraded: number;
    skipped: number;
    availableUpdates: string[];
    customizedConflicts: string[];
  }> {
    const pack = RulePackSchema.parse(defaultsData);
    let installed = 0;
    let upgraded = 0;
    let skipped = 0;
    const availableUpdates: string[] = [];
    const customizedConflicts: string[] = [];

    for (const rule of pack.rules) {
      const existing = await this.getRule(rule.ruleId, { kind: 'universal' });
      if (!existing) {
        await this.saveRule({ ...rule, scope: { kind: 'universal' }, provenance: 'bundled-default' });
        installed++;
      } else {
        skipped++;
        if (existing.provenance !== 'bundled-default') {
          customizedConflicts.push(rule.ruleId);
        } else if (existing.revision < rule.revision) {
          availableUpdates.push(rule.ruleId);
        }
      }
    }

    return { installed, upgraded, skipped, availableUpdates, customizedConflicts };
  }
}
